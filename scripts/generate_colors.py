#!/usr/bin/env python3
"""Generate runtime and native colors from lib/core/theme/colors.json.

Run with --check in CI to reject stale generated files.
"""
import argparse
import difflib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/core/theme/colors.json'


def dart_color(value):
    if not isinstance(value, str) or not re.fullmatch(r'#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?', value):
        raise ValueError(f'Expected #RRGGBB or #AARRGGBB, got {value!r}')
    digits = value[1:]
    return 'Color(0x' + ('FF' if len(digits) == 6 else '') + digits.upper() + ')'


def outputs():
    data = json.loads(SOURCE.read_text())
    shared = data['shared']
    for value in shared.values():
        dart_color(value)
    expected_roles = {
        'surfaces': {'surface', 'surfaceContainer', 'surfaceContainerHigh'},
        'content': {'onSurface', 'onSurfaceVariant'},
        'accent': {'primary', 'onPrimary'},
        'boundaries': {'outline', 'outlineVariant'},
        'feedback': {'error', 'onError', 'errorContainer', 'onErrorContainer'},
    }
    for name, variants in data['palettes'].items():
        if set(variants) != {'light', 'dark'}:
            raise ValueError(f'{name} needs light and dark variants')
        for brightness, categories in variants.items():
            if set(categories) != set(expected_roles):
                raise ValueError(f'{name}/{brightness}: unexpected color categories')
            for category, expected in expected_roles.items():
                if set(categories[category]) != expected:
                    raise ValueError(f'{name}/{brightness}/{category}: incorrect roles')
                for value in categories[category].values():
                    dart_color(value)
    lines = [
        '// Generated by scripts/generate_colors.py. Do not edit.',
        "import 'package:flutter/material.dart';",
        "import '../../models/settings.dart';",
        '',
        'class AppPalettes {',
        '  AppPalettes._();',
    ]
    for name, value in shared.items():
        lines.append(f'  static const {name} = {dart_color(value)};')
    lines += [
        '',
        '  static ColorScheme resolve(ColorSchemePreference palette, Brightness brightness) =>',
        '      _schemes[palette]![brightness]!;',
        '',
        '  static const _schemes = <ColorSchemePreference, Map<Brightness, ColorScheme>>{',
    ]
    for palette, modes in data['palettes'].items():
        lines.append(f'    ColorSchemePreference.{palette}: {{')
        for mode, categories in modes.items():
            c = {key: value for category in categories.values() for key, value in category.items()}
            def color(name):
                value = c[name] if name in c else shared[name]
                return dart_color(value)
            # Every Material role has an explicit app-owned value. No seed defaults.
            roles = {
                'primary':'primary', 'onPrimary':'onPrimary',
                'primaryContainer':'surfaceContainerHigh', 'onPrimaryContainer':'onSurface',
                'primaryFixed':'surfaceContainerHigh', 'primaryFixedDim':'surfaceContainer',
                'onPrimaryFixed':'onSurface', 'onPrimaryFixedVariant':'onSurfaceVariant',
                'secondary':'onSurface', 'onSecondary':'surface',
                'secondaryContainer':'primary', 'onSecondaryContainer':'onPrimary',
                'secondaryFixed':'surfaceContainerHigh', 'secondaryFixedDim':'surfaceContainer',
                'onSecondaryFixed':'onSurface', 'onSecondaryFixedVariant':'onSurfaceVariant',
                'tertiary':'primary', 'onTertiary':'onPrimary',
                'tertiaryContainer':'surfaceContainerHigh', 'onTertiaryContainer':'onSurface',
                'tertiaryFixed':'surfaceContainerHigh', 'tertiaryFixedDim':'surfaceContainer',
                'onTertiaryFixed':'onSurface', 'onTertiaryFixedVariant':'onSurfaceVariant',
                'error':'error', 'onError':'onError',
                'errorContainer':'errorContainer', 'onErrorContainer':'onErrorContainer',
                'surface':'surface', 'onSurface':'onSurface',
                'surfaceDim': 'surfaceContainer' if mode == 'light' else 'surface',
                'surfaceBright': 'surface' if mode == 'light' else 'surfaceContainerHigh',
                'surfaceContainerLowest':'surface', 'surfaceContainerLow':'surface',
                'surfaceContainer':'surfaceContainer', 'surfaceContainerHigh':'surfaceContainerHigh',
                'surfaceContainerHighest':'surfaceContainerHigh',
                'onSurfaceVariant':'onSurfaceVariant',
                'outline':'outline', 'outlineVariant':'outlineVariant',
                'shadow':'black', 'scrim':'black',
                'inverseSurface':'onSurface', 'onInverseSurface':'surface',
                'inversePrimary':'surface', 'surfaceTint':'surface',
            }
            lines += [f'      Brightness.{mode}: ColorScheme(', f'        brightness: Brightness.{mode},']
            lines += [f'        {role}: {color(token)},' for role, token in roles.items()]
            lines.append('      ),')
        lines.append('    },')
    lines += ['  };', '}', '']
    runtime = '\n'.join(lines)
    formatted = subprocess.run(['dart', 'format', '--output=show', '--summary=none'], input=runtime, text=True,
                               capture_output=True, check=True).stdout
    runtime = formatted
    result = {ROOT / 'lib/core/theme/app_palettes.g.dart': runtime}
    white, black = shared['white'].lower(), shared['black'].lower()
    result[ROOT / 'android/app/src/main/res/values/colors.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate_colors.py. -->\n<resources>\n'
        f'    <color name="ic_launcher_background">{black}</color>\n'
        f'    <color name="splash_background">{white}</color>\n</resources>\n'
    )
    result[ROOT / 'android/app/src/main/res/values-night/colors.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate_colors.py. -->\n<resources>\n'
        f'    <color name="splash_background">{black}</color>\n</resources>\n'
    )
    for mode in ['values-v31', 'values-night-v31']:
        path = ROOT / f'android/app/src/main/res/{mode}/styles.xml'
        result[path] = re.sub(r'(<item name="android:windowSplashScreenBackground">)[^<]+',
                              r'\1@color/splash_background', path.read_text())
    pubspec = ROOT / 'pubspec.yaml'
    text = pubspec.read_text()
    text = re.sub(r'(  color: )"#[A-Fa-f0-9]+"', rf'\1"{white}"', text)
    text = re.sub(r'(  color_dark: )"#[A-Fa-f0-9]+"', rf'\1"{black}"', text)
    text = re.sub(r'(  adaptive_icon_background: )"#[A-Fa-f0-9]+"', rf'\1"{black}"', text)
    result[pubspec] = text
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, expected in outputs().items():
        actual = path.read_text() if path.exists() else ''
        if actual == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
            print(''.join(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True),
                                             fromfile=str(path), tofile='generated')), end='')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if stale:
        raise SystemExit('Stale colors: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
